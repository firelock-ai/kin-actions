#!/usr/bin/env python3
"""Unit tests for the public-history hygiene gate.

Run with: ``python3 -m unittest discover -s scripts -p 'test_*.py'``

Covers the pure detectors with no git / network access. This file is excluded
from the gate's own content scan (``*test_*.py``) because it intentionally
contains the very patterns the gate rejects.
"""
import datetime as dt
import importlib.util
import unittest
from pathlib import Path


def _load(name, filename):
    path = Path(__file__).resolve().parent / filename
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


hh = _load("history_hygiene", "history-hygiene.py")


class MessageAiTraces(unittest.TestCase):
    def test_detects_session_trailer(self):
        self.assertTrue(hh.scan_message_ai("fix bug\n\nClaude-Session: https://x/y"))
        self.assertTrue(hh.scan_message_ai("Codex-Session: abc"))

    def test_detects_ai_coauthor(self):
        self.assertTrue(hh.scan_message_ai(
            "feat: x\n\nCo-authored-by: Claude <noreply@anthropic.com>"))

    def test_detects_generation_marker(self):
        self.assertTrue(hh.scan_message_ai("done\n\n🤖 Generated with Claude Code"))
        self.assertTrue(hh.scan_message_ai("Generated by Codex"))

    def test_detects_assistant_url_and_session_id(self):
        self.assertTrue(hh.scan_message_ai("see https://claude.ai/code/session_0123456789abcdef01"))
        self.assertTrue(hh.scan_message_ai("ref session_0123456789abcdefAB"))

    def test_clean_message_passes(self):
        self.assertEqual(hh.scan_message_ai("fix: handle empty input in parser"), [])
        self.assertEqual(hh.scan_message_ai("Signed-off-by: Dev <dev@example.com>"), [])


class IdentityAiTraces(unittest.TestCase):
    def test_detects_ai_name(self):
        self.assertTrue(hh.scan_identity_ai("Claude", "noreply@anthropic.com"))
        self.assertTrue(hh.scan_identity_ai("Cursor Agent", "x@y.com"))

    def test_detects_anthropic_email(self):
        # Name has no AI token, so this asserts the email branch fires.
        self.assertTrue(hh.scan_identity_ai("Pair Programmer", "noreply@anthropic.com"))

    def test_human_and_bot_identities_pass(self):
        self.assertEqual(hh.scan_identity_ai("Troy Fortin", "troy@firelock.ai"), [])
        self.assertEqual(hh.scan_identity_ai(
            "github-actions[bot]",
            "41898282+github-actions[bot]@users.noreply.github.com"), [])


class TicketRefs(unittest.TestCase):
    def test_detects_fir_and_linear(self):
        self.assertIn("internal ticket ref (FIR-...)", hh.scan_ticket_refs("see FIR-1234 for context"))
        self.assertIn("internal tracker link (linear.app)",
                      hh.scan_ticket_refs("https://linear.app/firelock-ai/issue/abc"))

    def test_clean_text_passes(self):
        self.assertEqual(hh.scan_ticket_refs("ordinary changelog text, no refs"), [])
        # A bare word that merely contains the letters must not match.
        self.assertEqual(hh.scan_ticket_refs("CONFIRMED and AFFIRMED"), [])


class BranchAndTitle(unittest.TestCase):
    def test_branch_fir_leak(self):
        self.assertTrue(hh.scan_branch_name("troy/fir-1015-consistent-release"))

    def test_branch_ai_tool(self):
        self.assertTrue(hh.scan_branch_name("claude/some-change"))
        self.assertTrue(hh.scan_branch_name("feature/codex-rewrite"))

    def test_clean_branch_passes(self):
        self.assertEqual(hh.scan_branch_name("ci/public-history-hygiene"), [])
        self.assertEqual(hh.scan_branch_name("automation/kin-registry-dependency-wave"), [])

    def test_title_leaks(self):
        self.assertTrue(hh.scan_title("Fix parser (FIR-1234)"))
        self.assertTrue(hh.scan_title("done, Generated with Claude"))

    def test_clean_title_passes(self):
        self.assertEqual(hh.scan_title("ci(version-gate): scope bump requirement"), [])


class AddedLineContent(unittest.TestCase):
    def test_detects_refs_and_traces(self):
        self.assertTrue(hh.scan_added_line("// TODO see FIR-9001"))
        self.assertTrue(hh.scan_added_line("# Claude-Session: zzz"))

    def test_clean_code_passes(self):
        self.assertEqual(hh.scan_added_line("let total = a + b; // sum"), [])


class Excludes(unittest.TestCase):
    def test_default_excludes(self):
        ex = hh.DEFAULT_CONTENT_EXCLUDES
        self.assertTrue(hh.is_excluded(".github/workflows/ci.yml", ex))
        self.assertTrue(hh.is_excluded("scripts/history-hygiene.py", ex))
        self.assertTrue(hh.is_excluded("scripts/test_history_hygiene.py", ex))
        self.assertTrue(hh.is_excluded("Cargo.lock", ex))

    def test_source_not_excluded(self):
        ex = hh.DEFAULT_CONTENT_EXCLUDES
        self.assertFalse(hh.is_excluded("src/lib.rs", ex))
        self.assertFalse(hh.is_excluded("README.md", ex))


@unittest.skipUnless(hh.ZoneInfo is not None, "zoneinfo unavailable")
class RestrictedWindow(unittest.TestCase):
    def _epoch(self, y, mo, d, h, mi=0):
        return int(dt.datetime(y, mo, d, h, mi, tzinfo=hh.ZoneInfo("America/New_York")).timestamp())

    def test_weekday_business_hours_human_flagged(self):
        # Wednesday 2026-06-24 10:00 ET
        when = hh.restricted_window_violation(self._epoch(2026, 6, 24, 10), "human@example.com")
        self.assertIsNotNone(when)

    def test_bot_identity_exempt(self):
        epoch = self._epoch(2026, 6, 24, 10)
        self.assertIsNone(hh.restricted_window_violation(
            epoch, "41898282+github-actions[bot]@users.noreply.github.com"))
        self.assertIsNone(hh.restricted_window_violation(epoch, "noreply@github.com"))

    def test_weekend_exempt(self):
        # Saturday 2026-06-27 10:00 ET
        self.assertIsNone(hh.restricted_window_violation(self._epoch(2026, 6, 27, 10), "human@example.com"))

    def test_evening_exempt(self):
        # Wednesday 20:00 ET is outside 09:00-17:59
        self.assertIsNone(hh.restricted_window_violation(self._epoch(2026, 6, 24, 20), "human@example.com"))


if __name__ == "__main__":
    unittest.main()
