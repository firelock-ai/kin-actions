#!/usr/bin/env python3
"""Unit tests for the public metadata safety gate.

Run with: ``python3 -m unittest discover -s scripts -p 'test_*.py'``

Covers the pure detectors with no git / network access. This exact file is
excluded from the gate's own content scan because it intentionally contains
the very patterns the gate rejects.
"""
import contextlib
import importlib.util
import io
import unittest
from unittest import mock
from pathlib import Path


def _load(name, filename):
    path = Path(__file__).resolve().parent / filename
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


hh = _load("history_hygiene", "history-hygiene.py")


class PrivateMetadata(unittest.TestCase):
    def test_detects_session_trailer(self):
        self.assertTrue(hh.scan_private_metadata("fix bug\n\nClaude-Session: https://x/y"))
        self.assertTrue(hh.scan_private_metadata("Codex-Session: abc"))

    def test_detects_assistant_url_and_session_id(self):
        self.assertTrue(
            hh.scan_private_metadata("see https://claude.ai/code/session_0123456789abcdef01"))
        self.assertTrue(
            hh.scan_private_metadata("see https://chatgpt.com/share/0123456789abcdef"))
        self.assertTrue(hh.scan_private_metadata("ref session_0123456789abcdefAB"))

    def test_clean_message_passes(self):
        self.assertEqual(hh.scan_private_metadata("fix: handle empty input in parser"), [])
        self.assertEqual(hh.scan_private_metadata("Signed-off-by: Dev <dev@example.com>"), [])

    def test_former_authorship_markers_are_out_of_scope(self):
        self.assertEqual(hh.scan_private_metadata(
            "Co-authored-by: Claude <noreply@anthropic.com>"), [])
        self.assertEqual(hh.scan_private_metadata("Generated by Codex"), [])
        self.assertEqual(hh.scan_private_metadata("🤖 Generated with Claude Code"), [])
        self.assertEqual(hh.scan_private_metadata("AI-Generated-by: Copilot"), [])
        self.assertEqual(hh.scan_private_metadata("Assisted-by: ChatGPT"), [])


class TicketRefBoundary(unittest.TestCase):
    """The tracker rule is scoped by whether the text becomes a commit message.

    Reversed on 2026-08-05 for anything that does: naming the tickets a merge
    resolves is intended, hundreds of commits on public default branches already
    carry those refs, and barring them made the rule forbid its own output on a
    queue-managed repository. Added content and branch names become no commit
    message and keep the rule.

    Both sides are asserted at every surface. A test that only checked the
    allowed side would pass equally if the rule had been dropped everywhere,
    which is the failure this whole class of bug is made of.
    """

    ALLOWED = "Closes FIR-1965"
    LINK = "https://linear.app/firelock-ai/issue/abc"

    def test_allowed_where_the_text_becomes_a_commit_message(self):
        self.assertEqual(hh.scan_title("Fix the parser (FIR-1234)"), [])
        self.assertEqual(hh.scan_body("Closes FIR-1965\nCloses FIR-1973"), [])
        self.assertEqual(hh.scan_title(self.LINK), [])
        self.assertEqual(hh.scan_body(self.LINK), [])
        # Commit messages run through scan_private_metadata alone.
        self.assertEqual(hh.scan_private_metadata("See FIR-1234 for context"), [])

    def test_rejected_where_it_does_not(self):
        self.assertIn("internal ticket ref (FIR-...)",
                      hh.scan_added_line("// TODO see FIR-9001"))
        self.assertIn("internal tracker link (linear.app)",
                      hh.scan_added_line(f"// see {self.LINK}"))
        # Assert the label rather than truthiness. `assertTrue` on a list passes
        # for any non-empty result, so it would survive the tracker label being
        # replaced by an unrelated one.
        self.assertEqual(
            hh.scan_branch_name("troy/fir-1015-consistent-release"),
            ["branch 'troy/fir-1015-consistent-release' contains "
             "internal ticket ref (FIR-...)"])
        self.assertEqual(
            hh.scan_branch_name(self.LINK),
            [f"branch '{self.LINK}' contains internal tracker link (linear.app)"])

    def test_clean_text_passes(self):
        self.assertEqual(hh.scan_ticket_refs("ordinary changelog text, no refs"), [])
        # A bare word that merely contains the letters must not match.
        self.assertEqual(hh.scan_ticket_refs("CONFIRMED and AFFIRMED"), [])
        self.assertEqual(hh.scan_added_line("let total = a + b; // sum"), [])
        self.assertEqual(hh.scan_branch_name("ci/public-history-hygiene"), [])


